from typing import Protocol

from app.modules.org.contracts import ApprovalNode, DepartmentPolicy, UserDTO
from app.modules.requisition.domain.model import Requisition


class Repository(Protocol):
    def get(self, req_id: str) -> Requisition | None: ...
    def add(self, req: Requisition) -> None: ...
    def save(self, req: Requisition, expected_version: int) -> None: ...
    def search(
        self, principal, page: int, size: int, status: str | None
    ) -> tuple[list[Requisition], int]: ...


class Organization(Protocol):
    def salary_check(self, series, level, city, quote): ...
    def headcount(self, dept): ...
    def reserve_headcount(self, ctx, dept, req_id, count): ...
    def get_user(self, user_id: str) -> UserDTO: ...
    def policy(self, dept_id: str) -> DepartmentPolicy: ...
    def resolve_approval_chain(
        self, kind: str, dept_id: str, facts: dict, snapshot: dict | None = None
    ) -> list[ApprovalNode]: ...
